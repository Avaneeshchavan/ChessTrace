const { randomBytes } = require('node:crypto');
const { PrismaClient } = require('@prisma/client');
const { identifier, ingestFile } = require('./ingest-data');

function connect() {
  const datasourceUrl = process.env.DIRECT_URL || process.env.DATABASE_URL;
  if (!datasourceUrl) throw new Error('Configure DIRECT_URL or DATABASE_URL in api-server/.env');
  return new PrismaClient({ datasourceUrl });
}

async function withScratch(db, run) {
  const schema = 'ct_b3_' + randomBytes(8).toString('hex');
  const s = identifier(schema);
  await db.$executeRawUnsafe(`CREATE SCHEMA ${s}`);
  try {
    const statements = [
      `CREATE TABLE ${s}."Game" (LIKE public."Game")`,
      `ALTER TABLE ${s}."Game" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY, ALTER COLUMN "createdAt" SET DEFAULT CURRENT_TIMESTAMP, ADD PRIMARY KEY (id)`,
      `CREATE INDEX ON ${s}."Game" ("whiteName")`,
      `CREATE INDEX ON ${s}."Game" ("blackName")`,
      `CREATE INDEX ON ${s}."Game" (event)`,
      `CREATE TABLE ${s}."Position" (LIKE public."Position")`,
      `ALTER TABLE ${s}."Position" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY, ADD PRIMARY KEY (id),
       ADD FOREIGN KEY ("gameId") REFERENCES ${s}."Game"(id) ON DELETE CASCADE`,
      `CREATE INDEX ON ${s}."Position" ("gameId")`,
      `CREATE INDEX idx_position_fencore_hash ON ${s}."Position" USING hash ("fenCore")`,
    ];
    for (const sql of statements) await db.$executeRawUnsafe(sql);
    return await run(schema, s);
  } finally {
    await db.$executeRawUnsafe(`DROP SCHEMA ${s} CASCADE`);
  }
}

async function loadScratch(db, schema, s, file, options) {
  const totals = await ingestFile(db, file, { ...options, schema, log: console.error });
  if (!totals.positions) throw new Error('No positions imported; check the PGN and filters.');
  await db.$executeRawUnsafe(`CREATE INDEX idx_position_vector_hnsw ON ${s}."Position"
    USING hnsw (vector vector_l2_ops) WITH (m=16, ef_construction=64)`);
  await db.$executeRawUnsafe(`ANALYZE ${s}."Game"`);
  await db.$executeRawUnsafe(`ANALYZE ${s}."Position"`);
  return totals;
}

module.exports = { connect, withScratch, loadScratch };
